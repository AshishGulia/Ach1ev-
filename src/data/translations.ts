export function getCustomLanguages(): LanguageOption[] {
  try {
    const raw = localStorage.getItem(LS_CUSTOM_LANGUAGES);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function getCustomTranslationsMap(): Record<string, Record<string, string>> {
  try {
    const raw = localStorage.getItem(LS_CUSTOM_TRANSLATIONS);
    if (!raw) return {};
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

export function getAllAvailableLanguages(): LanguageOption[] {
  return [...SUPPORTED_LANGUAGES, ...getCustomLanguages()];
}

export function saveCustomLanguage(
  option: LanguageOption,
  overrides: Record<string, string> = {}
) {
  const cleanCode = option.code.trim().toLowerCase().replace(/[^a-z0-9_-]/g, '') || `custom-${Date.now()}`;
  const entry: LanguageOption = {
    ...option,
    code: cleanCode,
    region: option.region === 'indian' || option.region === 'world' ? option.region : 'world',
    isCustom: true,
  };
  const existing = getCustomLanguages().filter((l) => l.code !== cleanCode);
  localStorage.setItem(LS_CUSTOM_LANGUAGES, JSON.stringify([...existing, entry]));

  const customDicts = getCustomTranslationsMap();
  const cleanedOverrides: Record<string, string> = {};
  Object.entries(overrides).forEach(([k, v]) => {
    if (v && v.trim()) cleanedOverrides[k] = v.trim();
  });
  customDicts[cleanCode] = { ...EN_BASE, ...cleanedOverrides };
  localStorage.setItem(LS_CUSTOM_TRANSLATIONS, JSON.stringify(customDicts));
  window.dispatchEvent(new CustomEvent('medden_language_changed', { detail: { lang: getCurrentLanguage() } }));
  return entry;
}

export function removeCustomLanguage(code: string) {
  const existing = getCustomLanguages().filter((l) => l.code !== code);
  localStorage.setItem(LS_CUSTOM_LANGUAGES, JSON.stringify(existing));
  const customDicts = getCustomTranslationsMap();
  delete customDicts[code];
  localStorage.setItem(LS_CUSTOM_TRANSLATIONS, JSON.stringify(customDicts));
  if (getCurrentLanguage() === code) {
    setAppLanguage('en');
  } else {
    window.dispatchEvent(new CustomEvent('medden_language_changed', { detail: { lang: getCurrentLanguage() } }));
  }
}

export function getTranslation(key: string, lang: AppLanguage = 'en'): string {
  const customDicts = getCustomTranslationsMap();
  if (customDicts[lang]?.[key]) return customDicts[lang][key];
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function getCurrentLanguage(): AppLanguage {
  const saved = localStorage.getItem('medden_app_lang');
  return (saved as AppLanguage) || 'en';
}

export function setAppLanguage(lang: AppLanguage) {
  localStorage.setItem('medden_app_lang', lang);
  window.dispatchEvent(new CustomEvent('medden_language_changed', { detail: { lang } }));
}
